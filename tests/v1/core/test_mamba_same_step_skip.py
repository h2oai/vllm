"""Mamba "align" prefix caching: a request whose cache hit ends on a state block
written in the current step waits for the next step, and only that request.

Before the fix the Mamba manager's refusal ("can't rely on blocks generated by
other requests in the current step") came back from allocate_slots as None, the
same as a shortage of free blocks, and the scheduler ended its waiting-queue
scan. Sibling requests over one shared prefix (several questions about one
record) then ran one per step however many other requests were waiting.
"""

import pytest
import torch

from vllm.v1.kv_cache_interface import MambaSpec

from .utils import create_requests, create_scheduler

pytestmark = pytest.mark.cpu_test

BLOCK_SIZE = 16
PROMPT_LEN = 40  # two full blocks and a tail


def _align_scheduler(num_blocks: int = 10000):
    scheduler = create_scheduler(
        max_num_batched_tokens=8192,
        block_size=BLOCK_SIZE,
        enable_prefix_caching=True,
        num_blocks=num_blocks,
        kv_cache_spec=MambaSpec(
            block_size=BLOCK_SIZE,
            shapes=((1, 1),),
            dtypes=(torch.float32,),
            mamba_cache_mode="align",
        ),
    )
    scheduler.need_mamba_block_aligned_split = True
    return scheduler


def _siblings_and_other():
    siblings = create_requests(
        num_requests=2,
        num_tokens=PROMPT_LEN,
        same_prompt=True,
        max_tokens=1,
        block_size=BLOCK_SIZE,
        req_ids=["sib0", "sib1"],
    )
    # a different prompt ([1] * PROMPT_LEN): no prefix shared with the siblings
    other = create_requests(
        num_requests=2,
        num_tokens=PROMPT_LEN,
        max_tokens=1,
        block_size=BLOCK_SIZE,
        req_ids=["unused", "other"],
    )[1]
    return siblings, other


def test_same_step_hit_defers_only_that_request():
    scheduler = _align_scheduler()
    (sib0, sib1), other = _siblings_and_other()
    for request in (sib0, sib1, other):
        scheduler.add_request(request)

    output = scheduler.schedule()
    scheduled = output.num_scheduled_tokens
    # sib0 writes the shared blocks' state in this step; sib1 would reuse it,
    # so sib1 waits; the request behind it is unrelated and runs now
    assert "sib0" in scheduled
    assert "sib1" not in scheduled
    assert "other" in scheduled
    assert scheduler.kv_cache_manager.deferred_by_same_step_hit("sib1")

    # next step: the deferral is cleared and sib1 runs with its prefix hit
    output = scheduler.schedule()
    assert "sib1" in output.num_scheduled_tokens
    assert sib1.num_computed_tokens > 0
    assert not scheduler.kv_cache_manager.deferred_by_same_step_hit("sib1")


def test_shortage_of_blocks_still_ends_the_scan():
    # room for one request's blocks only (two blocks: the null block and one
    # state block): the second is refused for space,
    # which is not a same-step deferral, and nothing behind it is scheduled
    scheduler = _align_scheduler(num_blocks=2)
    first, second = create_requests(
        num_requests=2,
        num_tokens=PROMPT_LEN,
        max_tokens=1,
        block_size=BLOCK_SIZE,
        req_ids=["first", "second"],
    )
    scheduler.add_request(first)
    scheduler.add_request(second)

    output = scheduler.schedule()
    assert "first" in output.num_scheduled_tokens
    assert "second" not in output.num_scheduled_tokens
    assert not scheduler.kv_cache_manager.deferred_by_same_step_hit("second")
